/**
 * Writes `catalogData.ts` from our C++ client's X-shop scripts (`Data/InGameShopScript/512.2012.<year>/`,
 * IBSCategory / IBSPackage / IBSProduct, `@`-separated, Latin-1): the same files our server reads
 * (S GameLogic/PlayerActions/CashShop/CashShopCatalog.cs, Data/ and Data/Y77/). Keeps only what the
 * window shows: every category, every package, and the product rows a package or a storage entry names.
 *
 *   MU_DATA=<client-next>/src/bin/Data bun src/modules/xshop/catalogGenerate.ts
 */
import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const DATA = process.env.MU_DATA ?? 'D:/Development/mu-reforge-client-next/src/bin/Data';
const YEARS = [76, 77];

const lines = (year: number, file: string) =>
  new TextDecoder('latin1')
    .decode(readFileSync(join(DATA, 'InGameShopScript', `512.2012.${String(year).padStart(3, '0')}`, file)))
    .split(/\r?\n/)
    .filter(l => l.trim())
    .map(l => l.split('@'));
const seqs = (s: string | undefined) => (s ?? '').split('|').map(Number).filter(n => n > 0);

function build(year: number) {
  // ProductDisplaySeq, name, parent, order, root (ShopCategory.cpp SetCategory).
  const categories = lines(year, 'IBSCategory.txt').map(f => [+f[0], f[1], +f[4], +f[5], +f[6]] as const);
  // ShopPackage.cpp SetPackage: 0 display seq, 1 view order, 2 package seq, 3 name, 5 price, 6 description,
  // 14 cash name, 19 product seqs, 20 item code, 23 price seqs, 25 cash type.
  const packages = lines(year, 'IBSPackage.txt')
    .filter(f => f.length >= 24)
    .map(f => [+f[0], +f[1], +f[2], f[3], +f[5], f[6], f[14], seqs(f[19]), +f[20], seqs(f[23]), +(f[25] ?? 0)] as const);
  // ShopProduct.cpp SetProduct: 0 product seq, 1 name, 2 property, 3 value, 4 unit, 5 price, 6 price seq,
  // 13 item code. The first line of a price seq wins, as the server's TryAdd.
  const byPrice = new Map<number, readonly [number, number, string, string, number, string, number, number]>();
  for (const f of lines(year, 'IBSProduct.txt')) {
    const priceSeq = +f[6];
    const code = +f[13];
    if (f.length < 14 || !(code > 0) || byPrice.has(priceSeq)) continue;
    byPrice.set(priceSeq, [priceSeq, +f[0], f[1], f[2], +f[3] || 0, f[4], +f[5] || 0, code]);
  }
  const keep = new Set<number>();
  const firstOfProduct = new Map<number, number>();
  const firstOfItem = new Map<number, number>();
  for (const row of [...byPrice.values()].sort((a, b) => a[0] - b[0])) {
    if (!firstOfProduct.has(row[1])) firstOfProduct.set(row[1], row[0]);
    // BuildDisplayMap: the storage shows an item by its lowest price seq.
    if (!firstOfItem.has(row[7])) firstOfItem.set(row[7], row[0]);
  }
  for (const p of packages) {
    p[9].forEach(s => keep.add(s));
    p[7].forEach(s => {
      const first = firstOfProduct.get(s);
      if (first !== undefined) keep.add(first);
    });
  }
  firstOfItem.forEach(s => keep.add(s));
  const products = [...keep].sort((a, b) => a - b).map(s => byPrice.get(s)).filter(r => r !== undefined)
    // Only English property names; the Korean ones are the localisation duplicates.
    .map(r => (/^[\x20-\x7e]*$/.test(r[3]) ? r : ([r[0], r[1], r[2], '', 0, '', r[6], r[7]] as const)));
  return { categories, packages, products };
}

const body = YEARS.map(y => `  ${y}: ${JSON.stringify(build(y))},`).join('\n');
writeFileSync(
  join(import.meta.dir, 'catalogData.ts'),
  `// Generated by catalogGenerate.ts from our client's Data/InGameShopScript/512.2012.<year>/. Do not edit.\n` +
    `import type { RawCatalog } from './catalog';\n\n` +
    `export const CATALOGS: Record<number, RawCatalog> = {\n${body}\n};\n`
);
